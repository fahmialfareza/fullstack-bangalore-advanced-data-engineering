from __future__ import annotations

import json
from pathlib import Path

from .config import settings
from .utils import now_iso


def report() -> Path:
    out=settings().outputs_dir; reports={p.stem:json.loads(p.read_text()) for p in out.glob("*.json")}
    stages=[]
    for name in ("profile","bronze_report","dq_report","load_report","stream_report","dw_report","marts_report","failure_tests"):
        if name in reports: stages.append(f"| {name} | {reports[name].get('duration_seconds','n/a')} | generated {reports[name].get('generated_at','')} |")
    text=f"""# EVALUATION EVIDENCE — Olist Data Platform

> Generated by `python pipeline.py report` at {now_iso()} from `outputs/*.json`.

## Environment and durations

| Stage | Seconds | Note |
|---|---:|---|
{chr(10).join(stages)}

## Data quality

The machine-readable evidence is in `outputs/profile.json` and `outputs/dq_report.json`. The silver gate quarantines hard-rule violations up to 2%; above that threshold it stops before PostgreSQL is changed.

## Stream

```json
{json.dumps(reports.get('stream_report',{}),indent=2)}
```

## Warehouse and marts

```json
{json.dumps({'warehouse':reports.get('dw_report',{}),'marts':reports.get('marts_report',{})},indent=2,default=str)}
```

## Design decisions

| Decision | Rejected alternative | Reason |
|---|---|---|
| Customer grain uses `customer_unique_id` | `customer_id` | The latter is order-scoped and overcounts people. |
| Review uses latest answer per order | Average all reviews | One row per order keeps joins from multiplying revenue; `review_count` preserves source multiplicity. |
| Full transactional raw/DW rebuild | Incremental merge | The static 126 MB source fits comfortably and rebuilds are easier to prove idempotent. |
| Event ID is order + status | Random UUID | Deterministic IDs make replay and crash recovery idempotent. |
| RFM frequency uses fixed bands | Frequency quintiles | Most customers have one order, so raw quintiles split ties arbitrarily. |

## Limitations

1. Kafka and PostgreSQL each run as a single node, so infrastructure loss is not highly available.
2. Consumer database commits and Kafka offset commits are not a distributed transaction; deterministic IDs provide at-least-once correctness.
3. Customer location is SCD Type 1 using the latest order, so prior addresses are not retained.
4. Brazil coordinate bounds are a rectangular approximation and may reject legitimate border points.
5. This static replay does not implement schema registry compatibility enforcement.

## Next experiments

1. Partition a 100× synthetic order set and measure whether p95 stream freshness remains below 60 seconds.
2. Add Debezium CDC and compare end-to-end lag with file replay at 1,000 events/second.
3. Run PostgreSQL and Kafka multi-node failure tests and target recovery in under 30 seconds with zero lost events.

## Reproduction

```bash
python3 -m venv .venv && .venv/bin/pip install -r requirements.txt
.venv/bin/python pipeline.py init
.venv/bin/python pipeline.py up
.venv/bin/python pipeline.py all
.venv/bin/pytest -q
```
"""
    path=settings().outputs_dir.parent/"EVALUATION_EVIDENCE.md"; path.write_text(text,encoding="utf-8"); return path
